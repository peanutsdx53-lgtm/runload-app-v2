import test from 'node:test';
import assert from 'node:assert/strict';
import {REST_DAY_KEY,readRestDays,saveRestDay} from '../ui/restDayStore.js';
import {reviewView} from '../ui/recordReviewExperience.js';
import {renderHistory} from '../ui/historyExperience.js';
import {inspectLocalStorage,inspectPortableBackup,DATA_KEYS,PORTABLE_FORMAT,PORTABLE_VERSION} from '../ui/dataManagement.js';
const storage=()=>{const m=new Map();return {getItem:k=>m.get(k)??null,setItem:(k,v)=>m.set(k,String(v)),removeItem:k=>m.delete(k),m}};
const draft={date:'2026-10-31',memo:'走らず休んだ',environmentNote:'雨',bodyObservation:'休養中の感覚',shoeName:'',distance:'12',minutes:'60',activityGait:'RUNNING',rofBefore:0,rofAfter:10};
test('rest day is saved with only selected subjective context; no run, ROF or GPS metrics',()=>{
 const s=storage(),save=saveRestDay(s,draft);
 assert.equal(save.ok,true,save.reason);
 const read=readRestDays(s);assert.equal(read.ok,true);
 assert.equal(read.records.length,1);
 const row=read.records[0];
 assert.equal(row.id,'rest-v1-2026-10-31');assert.equal(row.source,'manual');assert.equal(row.type,'rest');
 assert.equal(row.memo,draft.memo);
 assert.equal(Object.hasOwn(row,'distanceKm'),false);
 for(const k of ['durationSeconds','rofBefore','rofAfter','gps','reference'])assert.equal(Object.hasOwn(row,k),false,k);
 const html=renderHistory({month:'2026-10',day:null,type:'rest',query:'',selectedId:row.id},read.records,{connected:true,onOpen:()=>{}});
 assert.match(html,/休養日の記録/);
 assert.match(html,/休養日の記録：走行結果・参考値なし/);
 assert.doesNotMatch(html,/結果を開く/);
});
test('rest day review offers a real save path and explicitly excludes results',()=>{
 const html=reviewView(draft,{source:'manual',recordType:'rest'});
 assert.match(html,/data-rest-day-save/);
 assert.doesNotMatch(html,/data-rest-day-save[^>]*disabled/);
 assert.match(html,/走行の結果画面は表示しません/);
 assert.doesNotMatch(html,/data-manual-run-save/);
 const run=reviewView(draft,{source:'manual',recordType:'run'});
 assert.match(run,/data-manual-run-save/);
 assert.doesNotMatch(run,/data-rest-day-save/);
});
test('duplicate, invalid dates and corrupt rest store fail without mutation',()=>{
 const s=storage();assert.equal(saveRestDay(s,draft).ok,true);
 const before=s.getItem(REST_DAY_KEY);
 assert.equal(saveRestDay(s,draft).ok,false);
 assert.equal(saveRestDay(s,{...draft,date:'2026-02-30'}).ok,false);
 assert.equal(s.getItem(REST_DAY_KEY),before);
 s.setItem(REST_DAY_KEY,'{broken');
 assert.equal(saveRestDay(s,{...draft,date:'2026-10-30'}).ok,false);
 assert.equal(s.getItem(REST_DAY_KEY),'{broken');
 const fail=storage();fail.setItem=()=>{throw Error('denied')};
 assert.equal(saveRestDay(fail,draft).ok,false);
 assert.equal(fail.getItem(REST_DAY_KEY),null);
});
test('new rest storage participates in backups; old portable backups lacking rest key remain readable',()=>{
 const s=storage();saveRestDay(s,draft);
 const scan=inspectLocalStorage(s);assert.equal(scan.ok,true,scan.reason);
 assert.equal(scan.counts[REST_DAY_KEY],1);
 assert.ok(DATA_KEYS.includes(REST_DAY_KEY));
 const current={format:PORTABLE_FORMAT,version:PORTABLE_VERSION,exportedAt:new Date().toISOString(),local:scan.local,gpsLegacy:null,gpsCurrent:null};
 assert.equal(inspectPortableBackup(JSON.stringify(current)).ok,true);
 const old={...current,local:{...scan.local}};
 delete old.local[REST_DAY_KEY];
 const parsed=inspectPortableBackup(JSON.stringify(old));
 assert.equal(parsed.ok,true,parsed.reason);
 assert.equal(parsed.data.local[REST_DAY_KEY],null);
 const corrupt={...current,local:{...scan.local,[REST_DAY_KEY]:'{broken'}};
 assert.equal(inspectPortableBackup(JSON.stringify(corrupt)).ok,false);
});
