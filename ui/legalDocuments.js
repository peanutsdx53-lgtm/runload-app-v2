export function escapeLegalHtml(value){
  return String(value ?? "").replace(/[&<>"']/g, ch=>({"&":"&amp;","<":"&lt;",">":"&gt;",'"':"&quot;","'":"&#39;"}[ch]));
}
export function legalDocumentMarkup(kind){
  const document=kind==="privacy"?PRIVACY:TERMS;
  return '<div class="fu-document-body"><h2>'+escapeLegalHtml(document.title)+'</h2>'
    +document.sections.map(function(section){return '<section class="fu-document-section"><h3>'+escapeLegalHtml(section[0])+'</h3>'
      +section[1].map(function(p){return '<p>'+escapeLegalHtml(p)+'</p>';}).join('')+'</section>';}).join('')
    +'<p class="fu-document-contact">問い合わせ先：<a href="'+OPERATOR_ISSUES_URL+'" target="_blank" rel="noopener noreferrer">公開リポジトリのIssues</a>（公開投稿に個人情報を記載しないでください）</p>'
    +'</div>';
}
export function readLegalConsent(storage){
  try{
    const data=JSON.parse(storage?.getItem(LEGAL_CONSENT_KEY)||"null");
    return !!data && data.termsVersion===LEGAL_VERSION && data.privacyVersion===LEGAL_VERSION && data.termsAccepted===true && data.privacyConfirmed===true && typeof data.acceptedAt==="string";
  }catch{return false;}
}
export function saveLegalConsent(storage){
  const record={termsVersion:LEGAL_VERSION,privacyVersion:LEGAL_VERSION,termsAccepted:true,privacyConfirmed:true,acceptedAt:new Date().toISOString()};
  try{
    if(!storage)throw Error("storage unavailable");
    storage.setItem(LEGAL_CONSENT_KEY,JSON.stringify(record));
    return {ok:true,record:record};
  }catch{return {ok:false,message:"同意の記録を保存できませんでした。ブラウザの保存設定を確認してください。"};}
}
